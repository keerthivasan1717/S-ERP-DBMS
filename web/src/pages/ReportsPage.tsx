import React, { useEffect, useState } from 'react';
import { api } from '../api/client.js';
import { DataTable, Column } from '../components/DataTable.js';
import { StatusTag } from '../components/StatusTag.js';

interface ReportsPageProps {
  userRole: string;
}

export const ReportsPage: React.FC<ReportsPageProps> = ({ userRole }) => {
  const [reports, setReports] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [showModal, setShowModal] = useState(false);
  const [title, setTitle] = useState('');
  const [type, setType] = useState<'Sustainability' | 'Performance'>('Sustainability');
  const [error, setError] = useState<string | null>(null);

  const canGenerate = userRole === 'Administrator' || userRole === 'Strategic Manager' || userRole === 'Tactical Manager';

  const loadReports = async () => {
    try {
      const list = await api.get('/api/sustainability/reports');
      setReports(list);
    } catch (err: any) {
      console.error('Failed to load reports:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadReports();
  }, []);

  const handleCreate = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    try {
      await api.post('/api/sustainability/reports', {
        title,
        type,
        file_path: `/docs/reports/generated/${title.toLowerCase().replace(/\s+/g, '_')}.pdf`,
      });
      setShowModal(false);
      setTitle('');
      loadReports();
    } catch (err: any) {
      setError(err.message);
    }
  };

  const columns: Column<any>[] = [
    { key: 'report_id', header: 'ID' },
    { key: 'title', header: 'Report Title' },
    { key: 'type', header: 'Report Type', render: (r) => <StatusTag status={r.type} /> },
    { key: 'generated_by_name', header: 'Generated By' },
    { key: 'created_at', header: 'Generated At', render: (r) => r.created_at?.slice(0, 19).replace('T', ' ') },
    { key: 'file_path', header: 'Archive File Path', render: (r) => <span className="font-mono" style={{ fontSize: '0.8rem' }}>{r.file_path || '—'}</span> },
  ];

  if (loading) return <div className="panel">Loading reports archive...</div>;

  return (
    <div>
      <div className="panel-header">
        <div>
          <h1>Reports Archive</h1>
          <p style={{ color: 'var(--ink-soft)' }}>
            Generated ESG and implementation milestone reports archived in the database.
          </p>
        </div>
        {canGenerate && (
          <button className="btn btn-primary" onClick={() => setShowModal(true)}>
            + Generate Report Entry
          </button>
        )}
      </div>

      <DataTable columns={columns} data={reports} />

      {/* Modal */}
      {showModal && (
        <div style={{ position: 'fixed', top: 0, left: 0, right: 0, bottom: 0, backgroundColor: 'rgba(30,36,33,0.4)', display: 'flex', alignItems: 'center', justifyContent: 'center', zIndex: 1000 }}>
          <div style={{ backgroundColor: 'var(--surface)', border: '1px solid var(--line)', borderRadius: 'var(--radius)', padding: '1.5rem', maxWidth: '440px', width: '90%' }}>
            <h3>Log Generated Report</h3>
            {error && <div style={{ color: 'var(--danger)', marginBottom: '1rem', fontSize: '0.85rem' }}>{error}</div>}
            <form onSubmit={handleCreate} style={{ marginTop: '1rem' }}>
              <div className="form-group">
                <label>Report Title</label>
                <input type="text" required value={title} onChange={(e) => setTitle(e.target.value)} placeholder="e.g. Q4 Carbon & Energy Audit" />
              </div>
              <div className="form-group">
                <label>Report Type</label>
                <select value={type} onChange={(e) => setType(e.target.value as any)}>
                  <option value="Sustainability">Sustainability</option>
                  <option value="Performance">Performance</option>
                </select>
              </div>
              <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '0.5rem', marginTop: '1rem' }}>
                <button type="button" className="btn" onClick={() => setShowModal(false)}>Cancel</button>
                <button type="submit" className="btn btn-primary">Save Report</button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};
